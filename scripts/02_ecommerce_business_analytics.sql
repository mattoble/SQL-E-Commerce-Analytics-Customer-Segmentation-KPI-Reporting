/* Customer Report
	Purpose: Consolidate key customer metrics and behaviors.
	Highlights:
		1. Gather essential fields such as names, ages, and transaction details.
		2. Segments customers into categories (VIP, Regular, New) and age groups.
		3. Aggregates customer-level metrics:
		   - Total Orders
		   - Total Spent
		   - Total Items Ordered
		   - Total Products Ordered
		   - Lifespan (Months)
		4. Calculates valuable KPIs:
			- Recency (months since last order)
			- Average Order Value
			- Average Monthly Spend
*/

CREATE VIEW gold.report_customers AS
/*
----------------------------------------------------
1) Base Query: Retrieves core columns from tables
----------------------------------------------------
*/
WITH base_query AS (
	SELECT
		s.order_number,
		s.product_key,
		s.order_date,
		s.sales_amount,
		s.quantity,
		c.customer_key,
		c.customer_number,
		CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
		DATEDIFF(YEAR, c.birthdate, GETDATE()) AS age
	FROM gold.fact_sales AS s
	LEFT JOIN gold.dim_customers AS c ON c.customer_key = s.customer_key
	WHERE order_date IS NOT NULL

), customer_aggregation AS (
/*
------------------------------------------------------------------------
2) Customer Aggregations: Summarizes key metrics at the customer level
------------------------------------------------------------------------
*/
	SELECT
		customer_key,
		customer_number,
		customer_name,
		age,
		SUM(sales_amount) AS total_spent,
		COUNT(DISTINCT order_number) as total_orders,
		SUM(quantity) AS total_items_ordered,
		COUNT(DISTINCT product_key) AS total_products_ordered,
		MAX(order_date) AS last_order_date,
		DATEDIFF (month, MIN(order_date), MAX(order_date)) AS lifespan
	FROM base_query
	GROUP BY 
		customer_key,
		customer_number,
		customer_name,
		age
)
SELECT 
	customer_key,
	customer_number,
	customer_name,
	age,
	CASE
		WHEN age < 18 THEN 'Under 18'
		WHEN age BETWEEN 18 AND 24 THEN '18-24'
		WHEN age BETWEEN 25 AND 34 THEN '25-34'
		WHEN age BETWEEN 35 AND 44 THEN '35-44'
		WHEN age BETWEEN 45 AND 54 THEN '45-54'
		WHEN age BETWEEN 55 AND 64 THEN '55-64'
		ELSE '65 and Over'
	END AS age_group,
	CASE
		WHEN lifespan >= 12 AND total_spent > 5000 THEN 'VIP'
		WHEN lifespan >= 12 AND total_spent <= 5000 THEN 'Regular'
		ELSE 'New'
	END AS customer_segment,
	last_order_date,
	DATEDIFF(MONTH, last_order_date, GETDATE()) AS recency,
	total_spent,

	-- Average Order Value
	CASE
		WHEN total_spent = 0 THEN 0
		ELSE total_spent / total_orders
	END AS avg_order_value,

	-- Average Monthly Spend
	CASE
		WHEN lifespan = 0 THEN total_spent
		ELSE total_spent / lifespan
	END AS avg_monthly_spent,

	total_orders,
	total_items_ordered,
	total_products_ordered,
	lifespan
FROM customer_aggregation;

GO

/* Product Report
	Purpose: Consolidate key product metrics and behaviors.
	Highlights:
		1. Gather essential fields such as names, ages, and transaction details.
		2. Segments products by revenue to identify High-Performers, Mid-Range, or Low-Performers.
		3. Aggregates product-level metrics:
		   - Total Orders
		   - Total Sales
		   - Total Items Ordered
		   - Total Customers (Unique)
		   - Lifespan (Months)
		4. Calculates valuable KPIs:
			- Recency (months since last sale)
			- Average Order Revenue
			- Average Monthly Revenue
*/

CREATE VIEW gold.report_products AS
/*
------------------------------------------------------------------------
1) Base Query: Retrieves core columns from fact_sales and dim_products
------------------------------------------------------------------------
*/
WITH base_query AS (
	SELECT
		s.order_number,
		s.customer_key,
		s.order_date,
		s.sales_amount,
		s.quantity,
		p.product_key,
		p.product_name,
		p.category,
		p.subcategory,
		p.cost
	FROM gold.fact_sales AS s
	LEFT JOIN gold.dim_products AS p ON p.product_key = s.product_key
	WHERE order_date IS NOT NULL

), product_aggregation AS (
/*
------------------------------------------------------------------------
2) Product Aggregations: Summarizes key metrics at the product level
------------------------------------------------------------------------
*/
	SELECT
		product_key,
		product_name,
		category,
		subcategory,
		cost,
		SUM(sales_amount) AS total_sales,
		COUNT(DISTINCT order_number) as total_orders,
		SUM(quantity) AS total_items_ordered,
		COUNT(DISTINCT customer_key) AS total_customers,
		MAX(order_date) AS last_sale_date,
		DATEDIFF (month, MIN(order_date), MAX(order_date)) AS lifespan
	FROM base_query
	GROUP BY
		product_key,
		product_name,
		category,
		subcategory,
		cost
	)
SELECT
	product_key,
	product_name,
	category,
	subcategory,
	cost,
	total_sales,

	-- Average Order Revenue (AOR)
	CASE 
		WHEN total_orders = 0 THEN 0
		ELSE total_sales / total_orders
	END AS avg_order_revenue,

	-- Average Monthly Revenue
	CASE
		WHEN lifespan = 0 THEN total_sales
		ELSE total_sales / lifespan
	END AS avg_monthly_revenue,

	total_orders,
	total_items_ordered,
	total_customers,
	last_sale_date,
	DATEDIFF(MONTH, last_sale_date, GETDATE()) AS recency,
	CASE
		WHEN total_sales > 50000 THEN 'High-Performer'
		WHEN total_sales >= 10000 THEN 'Mid-Range'
		ELSE 'Low-Performer'
	END AS product_segment,
	lifespan
FROM product_aggregation;