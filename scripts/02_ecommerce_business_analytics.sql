-- Product-Cost Segmentation
WITH product_segments AS (
	SELECT
		product_key,
		product_name,
		cost,
		CASE
			WHEN cost < 100 THEN 'Below 100'
			WHEN cost BETWEEN 100 AND 500 THEN '100 - 500'
			WHEN cost BETWEEN 500 AND 1000 THEN '500 - 1000'
			ELSE 'Above 1000'
		END AS cost_range
	FROM gold.dim_products
)
SELECT
	cost_range,
	COUNT(product_key) AS total_products
FROM product_segments
GROUP BY cost_range
ORDER BY total_products DESC;

/* Customer Segmentation
	VIP: Customers with at least 12 months of history and spending more than 5,000.
	Regular: Customers with at least 12 months of history but spending 5,000 or less.
	New: Customers with a lifespan less than 12 months.
*/
WITH segmentation AS (
	SELECT
		c.customer_key AS customer,
		SUM(sales_amount) AS total_spent,
		MIN(order_date) AS first_order,
		MAX(order_date) AS last_order,
		DATEDIFF (month, MIN(order_date), MAX(order_date)) AS lifespan
	FROM gold.fact_sales AS s
	LEFT JOIN gold.dim_customers AS c ON c.customer_key = s.customer_key 
	GROUP BY c.customer_key
)
SELECT
	customer_segment,
	COUNT(customer) AS total_customers
FROM (
	SELECT
		customer,
		total_spent,
		lifespan,
		CASE
			WHEN lifespan >= 12 AND total_spent > 5000 THEN 'VIP'
			WHEN lifespan >= 12 AND total_spent <= 5000 THEN 'Regular'
			ELSE 'New'
		END AS customer_segment
	FROM segmentation
) AS customer_segmentation
GROUP BY customer_segment
ORDER BY total_customers DESC;

GO


